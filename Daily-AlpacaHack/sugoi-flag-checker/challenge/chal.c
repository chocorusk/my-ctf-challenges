static const size_t flag_len = 32;

static void key_expansion(uint8_t *RoundKey, const uint8_t *Key) {
    unsigned i, j, k;
    uint8_t tempa[4];

    for (i = 0; i < AES_NK; ++i) {
        RoundKey[(i * 4) + 0] = Key[(i * 4) + 0];
        RoundKey[(i * 4) + 1] = Key[(i * 4) + 1];
        RoundKey[(i * 4) + 2] = Key[(i * 4) + 2];
        RoundKey[(i * 4) + 3] = Key[(i * 4) + 3];
    }

    for (i = AES_NK; i < AES_NB * (AES_NR + 1); ++i) {
        k = (i - 1) * 4;
        tempa[0] = RoundKey[k + 0];
        tempa[1] = RoundKey[k + 1];
        tempa[2] = RoundKey[k + 2];
        tempa[3] = RoundKey[k + 3];

        if ((i % AES_NK) == 0) {
            const uint8_t u8tmp = tempa[0];
            tempa[0] = tempa[1];
            tempa[1] = tempa[2];
            tempa[2] = tempa[3];
            tempa[3] = u8tmp;

            tempa[0] = BOX(tempa[0]);
            tempa[1] = BOX(tempa[1]);
            tempa[2] = BOX(tempa[2]);
            tempa[3] = BOX(tempa[3]);

            tempa[0] ^= Rcon[i / AES_NK];
        }

        j = i * 4;
        k = (i - AES_NK) * 4;
        RoundKey[j + 0] = RoundKey[k + 0] ^ tempa[0];
        RoundKey[j + 1] = RoundKey[k + 1] ^ tempa[1];
        RoundKey[j + 2] = RoundKey[k + 2] ^ tempa[2];
        RoundKey[j + 3] = RoundKey[k + 3] ^ tempa[3];
    }
}

static void add_round_key(uint8_t round, state_t *state, const uint8_t *RoundKey) {
    uint8_t i, j;
    for (i = 0; i < 4; ++i) {
        for (j = 0; j < 4; ++j) {
            (*state)[i][j] ^= RoundKey[(round * AES_NB * 4) + (i * AES_NB) + j];
        }
    }
}

static uint8_t xtime(uint8_t x) {
    return (uint8_t)((x << 1) ^ (((x >> 7) & 1) * 0x1b));
}

#define MULTIPLY(x, y) \
    (((y & 1) * (x)) ^ (((y >> 1) & 1) * xtime((x))) ^ (((y >> 2) & 1) * xtime(xtime((x)))) ^ \
     (((y >> 3) & 1) * xtime(xtime(xtime((x))))) ^ (((y >> 4) & 1) * xtime(xtime(xtime(xtime((x)))))))

static void inv_mix_columns(state_t *state) {
    int i;
    uint8_t a, b, c, d;
    for (i = 0; i < 4; ++i) {
        a = (*state)[i][0];
        b = (*state)[i][1];
        c = (*state)[i][2];
        d = (*state)[i][3];

        (*state)[i][0] = MULTIPLY(a, 0x0e) ^ MULTIPLY(b, 0x0b) ^ MULTIPLY(c, 0x0d) ^ MULTIPLY(d, 0x09);
        (*state)[i][1] = MULTIPLY(a, 0x09) ^ MULTIPLY(b, 0x0e) ^ MULTIPLY(c, 0x0b) ^ MULTIPLY(d, 0x0d);
        (*state)[i][2] = MULTIPLY(a, 0x0d) ^ MULTIPLY(b, 0x09) ^ MULTIPLY(c, 0x0e) ^ MULTIPLY(d, 0x0b);
        (*state)[i][3] = MULTIPLY(a, 0x0b) ^ MULTIPLY(b, 0x0d) ^ MULTIPLY(c, 0x09) ^ MULTIPLY(d, 0x0e);
    }
}

static void inv_sub_bytes(state_t *state) {
    uint8_t i, j;
    for (i = 0; i < 4; ++i) {
        for (j = 0; j < 4; ++j) {
            (*state)[j][i] = IBOX((*state)[j][i]);
        }
    }
}

static void inv_shift_rows(state_t *state) {
    uint8_t temp;

    temp = (*state)[3][1];
    (*state)[3][1] = (*state)[2][1];
    (*state)[2][1] = (*state)[1][1];
    (*state)[1][1] = (*state)[0][1];
    (*state)[0][1] = temp;

    temp = (*state)[0][2];
    (*state)[0][2] = (*state)[2][2];
    (*state)[2][2] = temp;
    temp = (*state)[1][2];
    (*state)[1][2] = (*state)[3][2];
    (*state)[3][2] = temp;

    temp = (*state)[0][3];
    (*state)[0][3] = (*state)[1][3];
    (*state)[1][3] = (*state)[2][3];
    (*state)[2][3] = (*state)[3][3];
    (*state)[3][3] = temp;
}

static void inv_cipher(state_t *state, const uint8_t *RoundKey) {
    uint8_t round;

    add_round_key(AES_NR, state, RoundKey);

    for (round = AES_NR - 1;; --round) {
        inv_shift_rows(state);
        inv_sub_bytes(state);
        add_round_key(round, state, RoundKey);
        if (round == 0) {
            break;
        }
        inv_mix_columns(state);
    }
}

static void init_cipher(struct subtle_ctx *ctx, const uint8_t *key) {
    key_expansion(ctx->blob, key);
}

static void decrypt_block(const struct subtle_ctx *ctx, uint8_t *buf) {
    inv_cipher((state_t *)buf, ctx->blob);
}

static bool read_flag_input(char *buf, size_t limit, size_t *out_len) {
    if (fgets(buf, (int)limit, stdin) == NULL) {
        return false;
    }
    size_t len = strcspn(buf, "\n");
    buf[len] = '\0';
    *out_len = len;
    return true;
}

int main(void) {
    char input[128];
    size_t len = 0;

    printf("flag: ");
    if (!read_flag_input(input, sizeof(input), &len)) {
        return 1;
    }

    if (len != flag_len) {
        puts("wrong...");
        return 0;
    }

    uint8_t plain[sizeof(ciphertext) + 1];
    memcpy(plain, ciphertext, sizeof(ciphertext));

    struct subtle_ctx ctx;
    init_cipher(&ctx, key);

    for (size_t i = 0; i < sizeof(ciphertext); i += AES_BLOCKLEN) {
        decrypt_block(&ctx, plain + i);
    }
    plain[sizeof(ciphertext)] = '\0';

    if (strcmp(input, (char *)plain) == 0) {
        puts("correct!");
    } else {
        puts("wrong...");
    }
    return 0;
}
